<#
.SYNOPSIS
Vendors the WinUI agent skills from microsoft/WinAppCli into this repo.

.DESCRIPTION
Copies the selected skills from a pinned WinAppCli release tag and commit into
.agents/skills (Codex, Copilot, Cursor, Gemini and other Agent Skills readers)
and mirrors them into .claude/skills (Claude Code). Writes
.agents/skills/VENDORED.md recording the tag and commit. Commit the result.

See docs/guides/ai-tooling.md for when and why to bump the tag.

.EXAMPLE
.\scripts\Update-AgentSkills.ps1
.\scripts\Update-AgentSkills.ps1 -Tag v0.8.0 -ExpectedCommit 696222f72e80c669671845bd6c7b0286eefab987
#>
param(
    [ValidatePattern('^v\d+\.\d+\.\d+$')][string]$Tag = "v0.8.0",
    [ValidatePattern('^[0-9a-f]{40}$')][string]$ExpectedCommit = "696222f72e80c669671845bd6c7b0286eefab987",
    [ValidatePattern('^winui-[a-z0-9-]+$')]
    [string[]]$Skills = @(
        "winui-setup",
        "winui-dev-workflow",
        "winui-design",
        "winui-code-review",
        "winui-ui-testing",
        "winui-packaging"
    )
)

$ErrorActionPreference = "Stop"
$repositoryRoot = Split-Path -Parent $PSScriptRoot
$cloneDirectory = Join-Path ([System.IO.Path]::GetTempPath()) ("wintodo-winui-" + [guid]::NewGuid().ToString("N"))

function Remove-OwnedDirectory([string]$Path, [string]$Parent, [string]$ExpectedName) {
    $resolved = (Resolve-Path -LiteralPath $Path -ErrorAction Stop).ProviderPath
    if ([IO.Path]::GetDirectoryName($resolved) -ne [IO.Path]::GetFullPath($Parent).TrimEnd('\','/') -or
        [IO.Path]::GetFileName($resolved) -cne $ExpectedName -or
        ((Get-Item -Force -LiteralPath $resolved).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
        throw "Refusing to replace unexpected skill path."
    }
    Remove-Item -LiteralPath $resolved -Recurse -Force -ErrorAction Stop
}

try {
    git -c advice.detachedHead=false clone --quiet --filter=blob:none --sparse --depth 1 --branch $Tag `
        https://github.com/microsoft/WinAppCli $cloneDirectory
    if ($LASTEXITCODE -ne 0) {
        throw "git clone of WinAppCli $Tag failed."
    }
    $commit = (git -C $cloneDirectory rev-parse HEAD).Trim()
    if ($commit -cne $ExpectedCommit) { throw "The tag does not resolve to the reviewed commit." }
    git -C $cloneDirectory sparse-checkout set plugins/winui/agent-plugin/skills
    if ($LASTEXITCODE -ne 0) { throw "Could not check out the pinned WinUI skills." }
    $sourceRoot = Join-Path $cloneDirectory "plugins\winui\agent-plugin\skills"

    foreach ($skill in $Skills) {
        if (-not (Test-Path -LiteralPath (Join-Path $sourceRoot "$skill\SKILL.md"))) {
            throw "Skill '$skill' does not exist at $Tag. Map it by description, then update -Skills."
        }
    }

    foreach ($targetName in ".agents\skills", ".claude\skills") {
        $target = Join-Path $repositoryRoot $targetName
        New-Item -ItemType Directory -Force -Path $target | Out-Null
        foreach ($skill in $Skills) {
            $destination = Join-Path $target $skill
            if (Test-Path -LiteralPath $destination) { Remove-OwnedDirectory $destination $target $skill }
            Copy-Item -LiteralPath (Join-Path $sourceRoot $skill) -Destination $target -Recurse
        }
    }

    $date = [DateTime]::UtcNow.ToString("yyyy-MM-dd")
    $skillList = ($Skills | ForEach-Object { "- ``$_``" }) -join "`n"
    $manifest = @"
# Vendored agent skills

Generated by ``scripts/Update-AgentSkills.ps1``. Do not edit the ``winui-*``
folders by hand; re-run the script instead.

- Source: https://github.com/microsoft/WinAppCli (``plugins/winui/agent-plugin/skills``)
- Tag: ``$Tag``
- Commit: ``$commit``
- Vendored: $date
- Mirrored to: ``.claude/skills/``

$skillList
"@
    Set-Content -LiteralPath (Join-Path $repositoryRoot ".agents\skills\VENDORED.md") -Value $manifest -Encoding utf8
    Write-Host "Vendored $($Skills.Count) skills from WinAppCli $Tag ($commit)."
}
finally {
    if (Test-Path -LiteralPath $cloneDirectory) {
        Remove-OwnedDirectory $cloneDirectory ([IO.Path]::GetTempPath()) ([IO.Path]::GetFileName($cloneDirectory))
    }
}
